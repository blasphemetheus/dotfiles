-- Monitors. Same descriptors the scripts use (hdmi-wake.sh, refresh-toggle.sh
-- re-issue hl.monitor{} via `hyprctl eval` to bounce refresh rates).
--
-- ASUS VG27V defaults to 120Hz: the 165Hz HDMI link is bandwidth-marginal
-- (see hdmi-wake.sh / hdmi-retrain.sh); Super+Shift+F toggles up to 165Hz.
-- vrr=1 is aspirational on the HDMI-only VG27V (NVIDIA does no FreeSync over
-- HDMI); the slippi-tearing rule is the low-latency path instead.
-- Explicit positions (auto-placement flipped sides once): VG27V main at 0x0,
-- VY279HGR physically to its RIGHT so it starts at 1920x0.

-- BEGIN hyprdisplays (generated by the hyprdisplays app; edit there, or between these markers at your own risk)
-- Catch-all for anything unlisted ("preferred", not highrr: a TV's top
-- refresh mode can be 800x600@60.32, which highrr picks over 1080p@60).
hl.monitor({ output = "", mode = "preferred", position = "auto", scale = 1, vrr = 1 })

-- DP-2 (ASUSTek COMPUTER INC VY279HGR TCLMTR040596)
hl.monitor({
    output   = "desc:ASUSTek COMPUTER INC VY279HGR TCLMTR040596",
    mode     = "1920x1080@100",
    position = "1920x0",
    scale    = 1,
    vrr      = 0,
})

-- DP-3 via DP→HDMI adapter (ASUSTek COMPUTER INC ASUS VG27V 0x0003ABEC); was HDMI-A-1 until 2026-09-20
hl.monitor({
    output   = "desc:ASUSTek COMPUTER INC ASUS VG27V 0x0003ABEC",
    mode     = "1920x1080@120",
    position = "0x0",
    scale    = 1,
    vrr      = 0,
})

-- Toshiba TV (Fire TV's screen) on HDMI-A-1 since 2026-09-20, often alongside
-- both ASUS panels. auto-right, NOT a fixed 3840x0: when the VY279HGR is
-- absent (DP deep-sleep, 2026-10-17) a fixed x left a 1920px dead gap the
-- cursor could not cross and the TV ended up holding focus. Always last/rightmost;
-- autostart.lua also hands initial focus to the VG27V.
hl.monitor({
    output   = "desc:Toshiba America Info Systems Inc TOSHIBA-TV 0x00000001",
    mode     = "1920x1080@60",
    position = "auto-right",
    scale    = 1,
})

